// Parse CatQuest NPC metadata as data; never execute third-party Lua.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const lua = require('luaparse');
const positive = n => Number.isSafeInteger(n) && n > 0;
function quote(text) {
  return '"' + text.replace(/[\\"\x00-\x1f\x7f]/g, c =>
    c === '\\' || c === '"' ? '\\' + c : '\\' + c.charCodeAt(0).toString().padStart(3, '0')) + '"';
}
function parse(bytes) {
  const ast = lua.parse(bytes.toString('latin1'), { encodingMode: 'pseudo-latin1' });
  function decode(node) {
    if (node.type === 'TableConstructorExpression') {
      let index = 0;
      return Object.fromEntries(node.fields.map(f => [f.key?.value ?? f.key?.name ?? ++index, decode(f.value)]));
    }
    if (node.type === 'StringLiteral') return Buffer.from(node.value, 'latin1').toString('utf8');
    if (['NumericLiteral', 'BooleanLiteral', 'NilLiteral'].includes(node.type)) return node.value;
    throw Error('Unsupported NPC data expression: ' + node.type);
  }
  const tables = {};
  for (const statement of ast.body) {
    const target = statement.variables?.[0];
    if (statement.type === 'AssignmentStatement' && target?.type === 'MemberExpression'
        && target.base.name === 'ns' && ['NpcData', 'QuestGiver', 'QuestFinisher'].includes(target.identifier.name)) {
      tables[target.identifier.name] = decode(statement.init[0]);
    }
  }
  if (!tables.NpcData || !tables.QuestGiver || !tables.QuestFinisher) throw Error('Missing CatQuest NPC/giver/finisher tables');
  return tables;
}
function render(bytes, version) {
  const tables = parse(bytes);
  function encode(value, depth = 0) {
    if (value == null) return 'nil';
    if (typeof value === 'string') return quote(value);
    if (typeof value !== 'object') return String(value);
    const rows = Object.entries(value).sort((a, b) => Number(a[0]) - Number(b[0]));
    if (!depth) return '{\n' + rows.map(([id, record]) => `    [${id}] = ${encode(record, 1)},`).join('\n') + '\n}';
    return '{ ' + rows.map(([key, entry]) => `[${key}] = ${encode(entry, depth + 1)}`).join(', ') + ' }';
  }
  for (const table of [tables.NpcData, tables.QuestGiver, tables.QuestFinisher]) {
    if (!Object.keys(table).length || Object.keys(table).some(id => !positive(Number(id)))) throw Error('Invalid NPC data IDs');
  }
  for (const id of [...Object.values(tables.QuestGiver), ...Object.values(tables.QuestFinisher)]) {
    if (!positive(id)) throw Error('Invalid NPC reference');
  }
  return '-- Generated by tools/import-catquest-speakers.js; do not edit.\n'
    + `-- Source: CatQuest ${version}, NpcData.lua; SHA-256: ${crypto.createHash('sha256').update(bytes).digest('hex')}\n`
    + '-- Complete NPC metadata and giver/finisher maps; captured identities take priority.\n'
    + `WowVoiceCatQuestSpeakers = { schemaVersion = 1, sourceVersion = ${quote(version)},\n`
    + `npcs = ${encode(tables.NpcData)},\ngivers = ${encode(tables.QuestGiver)},\nfinishers = ${encode(tables.QuestFinisher)}\n}\n`;
}
module.exports = { parse, render };
if (require.main === module) {
  const directory = process.argv[2];
  if (!directory) throw Error('Usage: node tools/import-catquest-speakers.js <CatQuest directory>');
  const version = fs.readFileSync(path.join(directory, 'CatQuest.toc'), 'utf8').match(/^##\s*Version:\s*(\S+)/m)?.[1];
  if (!version) throw Error('Missing CatQuest version');
  const result = render(fs.readFileSync(path.join(directory, 'NpcData.lua')), version);
  fs.writeFileSync(path.join(__dirname, '../src/CatQuestSpeakers.lua'), result);
  console.log(`Imported complete CatQuest NPC database (${Buffer.byteLength(result)} bytes)`);
}
