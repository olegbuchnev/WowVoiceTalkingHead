// Read installed packs as data and measure each OGG; never copy audio or execute addon Lua.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const lua = require('luaparse');
const {duration, luaString} = require('./import-forever-audio');
const packNames = ['Wayfarer_Voices_Alliance', 'Wayfarer_Voices_Horde', 'Wayfarer_Voices_Shared', 'Wayfarer_Voices_Narrator'];
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
function readPack(bytes) {
  const ast = lua.parse(bytes.toString('latin1'), {encodingMode:'pseudo-latin1'});
  const calls = ast.body.filter(n => n.type === 'CallStatement' && n.expression.base.type === 'MemberExpression'
    && n.expression.base.base.name === 'Wayfarer' && n.expression.base.identifier.name === 'RegisterPack');
  if (calls.length !== 1) throw Error('Expected one Wayfarer.RegisterPack data table');
  function decode(n) {
    if (n.type === 'TableConstructorExpression') {
      let i = 0; const result = {};
      for (const f of n.fields) {
        const key = f.key?.name ?? f.key?.value ?? ++i;
        if (Object.hasOwn(result, key)) throw Error(`Duplicate key: ${key}`);
        result[key] = decode(f.value);
      }
      return result;
    }
    if (n.type === 'StringLiteral') return Buffer.from(n.value, 'latin1').toString('utf8');
    if (['NumericLiteral','BooleanLiteral','NilLiteral'].includes(n.type)) return n.value;
    throw Error(`Unsupported data expression: ${n.type}`);
  }
  return decode(calls[0].expression.arguments[0]);
}
function literal(value) {
  if (typeof value === 'string') return luaString(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (value == null) return 'nil';
  return '{' + Object.entries(value).map(([k,v]) => `[${/^\d+$/.test(k) ? k : luaString(k)}]=${literal(v)}`).join(',') + '}';
}
function generate(source, root = path.resolve(__dirname, '..')) {
  const runtime = {}, manifest = {schemaVersion:1, packs:{}, mainDescriptions:0};
  const ids = new Set();
  for (const name of packNames) {
    const directory = path.join(source, name);
    if (!fs.existsSync(directory)) continue;
    const index = fs.readFileSync(path.join(directory,'Index.lua'));
    const toc = fs.readFileSync(path.join(directory, name+'.toc'));
    const version = /^##\s*Version:\s*(\S+)/m.exec(toc.toString('utf8'))?.[1];
    const pack = readPack(index);
    if (pack.name !== name || pack.format !== 1 || !version || pack.version !== version
        || (pack.ext && pack.ext !== 'ogg') || !pack.q) throw Error(`Unsupported pack: ${name}`);
    const entries = {}, files = {};
    let descriptions = 0;
    for (const [id, quest] of Object.entries(pack.q)) {
      if (!/^[1-9]\d*$/.test(id)) throw Error(`Invalid quest ID ${id}`);
      for (const [section, entry] of Object.entries(quest)) {
        if (!['a','p','c'].includes(section)) throw Error(`Unknown section ${section}`);
        const variants = entry.m != null || entry.f != null ? ['m','f'].filter(k => entry[k] != null) : ['d'];
        const record = {voice:entry.v || '', speaker:entry.s || 0, audio:{}};
        for (const variant of variants) {
          const indexed = entry[variant];
          if (!Number.isFinite(indexed) || indexed <= 0) throw Error(`Invalid duration: ${name}/${id}${section}`);
          const file = `q/${id}-${section}${variant === 'd' ? '' : '-'+variant}.ogg`;
          const bytes = fs.readFileSync(path.join(directory, file));
          const measured = duration(bytes);
          record.audio[variant] = {file, duration:measured, indexDuration:indexed};
          files[file] = {sha256:hash(bytes), duration:measured, indexDuration:indexed, bytes:bytes.length};
        }
        entries[id+section] = record;
      }
      if (quest.a) {ids.add(id); descriptions++;}
    }
    runtime[name] = {version, model:pack.model || 'v3', entries};
    manifest.packs[name] = {version, model:pack.model || 'v3', indexSha256:hash(index), tocSha256:hash(toc),
      mainDescriptions:descriptions, sections:Object.keys(entries).length, files};
  }
  if (!ids.size) throw Error('No quest descriptions found');
  manifest.mainDescriptions = ids.size;
  // Validate every input before replacing either output.
  fs.mkdirSync(path.join(root,'src'), {recursive:true});
  fs.mkdirSync(path.join(root,'docs/internal'), {recursive:true});
  const rows = Object.entries(runtime).map(([name, pack]) => `  [${luaString(name)}] = {version=${luaString(pack.version)}, model=${luaString(pack.model)}, entries={\n`
    + Object.entries(pack.entries).map(([key, entry]) => `    [${luaString(key)}]=${literal(entry)},`).join('\n') + '\n  }},');
  fs.writeFileSync(path.join(root,'src/WayfarerAudio.lua'), '-- Generated by tools/generate-wayfarer-metadata.js. Audio stays in upstream packs.\nWowVoiceWayfarerAudio = {schemaVersion=1, packs={\n'+rows.join('\n')+'\n}}\n');
  fs.writeFileSync(path.join(root,'docs/internal/wayfarer-audio-manifest.json'), JSON.stringify(manifest,null,2)+'\n');
  return {mainDescriptions:ids.size, packs:Object.fromEntries(Object.entries(manifest.packs).map(([name,p]) => [name,{version:p.version, descriptions:p.mainDescriptions, sections:p.sections, files:Object.keys(p.files).length}]))};
}
if (require.main === module) {
  if (!process.argv[2]) throw Error('Usage: node tools/generate-wayfarer-metadata.js <AddOns directory> [output root]');
  console.log(JSON.stringify(generate(process.argv[2],process.argv[3]),null,2));
}
module.exports = {generate, readPack, literal};
