// Measure an external WowVoiceSounds pack without copying audio or running upstream Lua.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { dataTable, duration } = require('./import-forever-audio');
const { readSourceVersion } = require('./audio-source-version');
const defaultRoot = path.resolve(__dirname, '..');
const manifestPath = 'docs/internal/classic-audio-manifest.json';
const hash = buffer => crypto.createHash('sha256').update(buffer).digest('hex');

function indexedFiles(root) {
  // Availability comes from the shipped quest index, never the previous timers.
  const index = dataTable(path.join(root, 'src/Index.lua'));
  const names = new Set();
  for (const entries of Object.values(index)) {
    for (const entry of Object.values(entries)) {
      if (!Number.isSafeInteger(entry.q) || entry.q <= 0) throw Error('Invalid Classic quest ID');
      for (const section of ['a', 'p', 'c']) {
        if (entry[section] == null) continue;
        if (!Number.isFinite(entry[section]) || entry[section] <= 0) {
          throw Error(`Invalid Classic index section: ${entry.q}${section}`);
        }
        names.add(`${entry.q}${section}.ogg`);
      }
    }
  }
  if (!names.size) throw Error('Empty Classic quest index');
  return [...names].sort();
}

function measure(file, directory) {
  const buffer = fs.readFileSync(path.join(directory, file));
  let seconds;
  try { seconds = duration(buffer); }
  catch (error) { throw Error(`Invalid Classic OGG ${file}: ${error.message}`); }
  return { file, bytes: buffer.length, duration: seconds, sha256: hash(buffer) };
}

function collect(source, root = defaultRoot) {
  const provenance = readSourceVersion(source, ['WowVoiceSounds_Vanilla.toc', 'WowVoiceSounds.toc']);
  const names = indexedFiles(root);
  const actual = fs.readdirSync(source).filter(name => /\.ogg$/i.test(name)).sort();
  const expectedSet = new Set(names), actualSet = new Set(actual);
  const missing = names.filter(name => !actualSet.has(name));
  const extra = actual.filter(name => !expectedSet.has(name));
  if (missing.length || extra.length) {
    throw Error(`Classic coverage mismatch: missing ${missing.length} [${missing.slice(0, 5)}]; unexpected ${extra.length} [${extra.slice(0, 5)}]`);
  }
  const files = names.map(name => measure(name, source));
  const sections = { a: 0, p: 0, c: 0 }, quests = new Set();
  for (const file of files) {
    const [, id, section] = /^(\d+)([apc])\.ogg$/.exec(file.file);
    quests.add(id); sections[section]++;
  }
  const serviceAudio = measure('silence.ogg', path.join(root, 'src/Media'));
  if (serviceAudio.duration !== 0.1) throw Error('Expected the bundled 100 ms service silence');
  return {
    schemaVersion: 1, source: 'WowVoiceSounds', version: provenance.version, sourceToc: provenance.toc,
    selection: 'All a/p/c sections in the shipped Classic quest index; audio files are not modified',
    measurement: 'Vorbis final granule / sample rate, rounded to 6 decimal places; no playback padding',
    quests: quests.size, sections, files, serviceAudio,
  };
}

function renderDurations(manifest) {
  return '-- Generated by tools/generate-classic-metadata.js; do not edit manually.\n'
    + `-- WowVoiceSounds ${manifest.version}; per-file measurements and SHA-256: ${manifestPath}\n`
    + '-- Values are OGG durations in seconds; playback tail is applied separately.\n'
    + `-- Entries: ${manifest.files.length + 1}\nWowVoiceDur = {\n`
    + manifest.files.map(entry => `["${entry.file.slice(0, -4)}"]=${entry.duration},`).join('\n')
    + `\n["silence"]=${manifest.serviceAudio.duration},\n}\n`;
}

function generate(source, root = defaultRoot) {
  // Finish coverage and stream validation before replacing either output.
  const manifest = collect(source, root);
  const output = path.join(root, manifestPath);
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(path.join(root, 'src/Durations.lua'), renderDurations(manifest));
  fs.writeFileSync(output, JSON.stringify(manifest, null, 2) + '\n');
  return manifest;
}

function check(source, root = defaultRoot) {
  const measured = collect(source, root);
  const saved = JSON.parse(fs.readFileSync(path.join(root, manifestPath), 'utf8'));
  // Report the changed file, including replacements with the same duration/version.
  const expected = new Map((saved.files || []).map(entry => [entry.file, entry]));
  for (const entry of measured.files) {
    if (JSON.stringify(entry) !== JSON.stringify(expected.get(entry.file))) {
      throw Error(`Classic measurement/hash mismatch: ${entry.file}`);
    }
  }
  if (JSON.stringify(measured) !== JSON.stringify(saved)) throw Error('Classic manifest/pack metadata mismatch');
  const text = fs.readFileSync(path.join(root, 'src/Durations.lua'), 'utf8').replace(/\r\n/g, '\n');
  if (text !== renderDurations(measured)) throw Error('Classic Durations.lua differs from measured OGG durations');
  return measured;
}

module.exports = { generate, check, collect, indexedFiles, renderDurations };
if (require.main === module) {
  const [source, option, ...extra] = process.argv.slice(2);
  if (!source || (option && option !== '--check') || extra.length) {
    throw Error('Usage: node tools/generate-classic-metadata.js <WowVoiceSounds directory> [--check]');
  }
  const manifest = option === '--check' ? check(source) : generate(source);
  console.log(`${option ? 'Verified' : 'Generated'} Classic ${manifest.version}: ${manifest.quests} quests, `
    + `${manifest.files.length} measured OGG files; sections: ${JSON.stringify(manifest.sections)}`);
}
