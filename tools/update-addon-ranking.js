// Convert a public server export into the bundled addon snapshot; never read votes or credentials.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'..');
const input=path.resolve(process.argv[2] || path.join(root,'artifacts/voice-ranking/addon-voice-ranking.json'));
const snapshot=JSON.parse(fs.readFileSync(input,'utf8'));
if(snapshot.schemaVersion!==1 || !Array.isArray(snapshot.groups) || snapshot.groups.length>256) throw Error('Unsupported ranking snapshot');
const json=JSON.stringify(snapshot);
if(Buffer.byteLength(json)>65536 || json.includes(']==]')) throw Error('Invalid snapshot size or delimiter');
const hash=crypto.createHash('sha256').update(json).digest('hex');
fs.writeFileSync(path.join(root,'src/BuiltinRanking.lua'),`-- Generated by tools/update-addon-ranking.js from the public ranking export.\nTalkingHeadRuBuiltinRanking = {\n    sha256 = "${hash}",\n    json = [==[${json}]==],\n}\n`);
console.log(`Bundled ranking: ${snapshot.generatedAt}, ${snapshot.groups.length} groups.`);
