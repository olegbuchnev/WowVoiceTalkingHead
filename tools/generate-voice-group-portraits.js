// Pick representatives at build time. Runtime only reads this small lookup table.
const fs=require('fs'),path=require('path');
const {dataTable}=require('./import-forever-audio');
const root=path.resolve(__dirname,'..');
const positive=value=>Number.isSafeInteger(value)&&value>0;
const key=npc=>npc?.race&&['male','female'].includes(npc.sex)?npc.race+'/'+npc.sex:null;
function select(database,previous={schemaVersion:1,groups:{}},votes=[]) {
  if(previous.schemaVersion!==1 || !previous.groups) throw Error('Invalid portrait selections');
  const counts=new Map(),popularity=new Map(),groups=new Map();
  for(const giver of Object.values(database.givers)) if(positive(giver.npcID)) counts.set(giver.npcID,(counts.get(giver.npcID)||0)+1);
  for(const row of votes) {
    if(!Number.isSafeInteger(row.npcID)||row.npcID<0||!Number.isSafeInteger(row.votes)||row.votes<0) throw Error('Invalid portrait vote count');
    if(key(row)&&key(database.npcs[row.npcID])===key(row)) popularity.set(row.npcID,(popularity.get(row.npcID)||0)+row.votes);
  }
  for(const [id,npc] of Object.entries(database.npcs)) {
    const group=key(npc);if(!group)continue;
    if(!groups.has(group))groups.set(group,[]);
    groups.get(group).push(Number(id));
  }
  const result={schemaVersion:1,groups:{}};
  for(const [group,ids] of [...groups].sort(([a],[b])=>a.localeCompare(b,'en'))) {
    const old=previous.groups[group];
    // Keep a valid representative across imports, even when popularity changes.
    // Replace it only if removed, reclassified, or a formerly missing portrait is now available.
    const withDisplay=ids.filter(id=>positive(database.npcs[id].displayID));
    const candidates=withDisplay.length?withDisplay:ids;
    let id=old&&candidates.includes(old.npcID)?old.npcID:null;
    if(!id) {
      candidates.sort((a,b)=>(popularity.get(b)||0)-(popularity.get(a)||0)
        ||(counts.get(b)||0)-(counts.get(a)||0)||a-b);
      id=candidates[0];
    }
    const npc=database.npcs[id];
    result.groups[group]={npcID:id,name:npc.name||'',displayID:positive(npc.displayID)?npc.displayID:null};
  }
  return result;
}
function render(selections) {
  return '-- Generated by tools/generate-voice-group-portraits.js; stable NPC representatives.\n'
    +'TalkingHeadRuVoiceGroupPortraits = {\n'+Object.entries(selections.groups).map(([key,npc])=>
      `    ["npc:${key.replace('/',':')}"] = { npcID = ${npc.npcID}, displayID = ${npc.displayID||'nil'} },`).join('\n')+'\n}\n';
}
function generate(database,check=false,votes=[]) {
  const selectionsFile=path.join(root,'docs/internal/voice-group-portraits.json');
  const previous=fs.existsSync(selectionsFile)?JSON.parse(fs.readFileSync(selectionsFile,'utf8')):undefined;
  const result=select(database,previous,votes);
  for(const [file,content] of [[selectionsFile,JSON.stringify(result,null,2)+'\n'],[path.join(root,'src/VoiceGroupPortraits.lua'),render(result)]]) {
    if(check) {
      if(!fs.existsSync(file)||fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('Stale voice group portraits: '+path.relative(root,file));
    } else fs.writeFileSync(file,content);
  }
  return result;
}
module.exports={select,render,generate};
if(require.main===module) {
  const voteFile=process.argv.find(arg=>arg.startsWith('--votes='))?.slice(8);
  const result=generate(dataTable(path.join(root,'src/Speakers.lua')),process.argv.includes('--check'),voteFile?JSON.parse(fs.readFileSync(voteFile,'utf8')):[]);
  console.log(`Voice group portraits: ${Object.keys(result.groups).length}`);
}
