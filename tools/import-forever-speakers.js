// Extract factual quest -> starter IDs from the published Forever quest snapshot.
// Read JSON and parse our Classic Lua as data; never execute upstream addon code.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const lua = require('luaparse');
const root = path.resolve(__dirname, '..');
const manifestPath = path.join(root, 'docs/internal/forever-speakers-manifest.json');
const source = 'https://github.com/TylerAkins/forever-quest-markers';
const sha256 = text => crypto.createHash('sha256').update(text).digest('hex');

function questRecord(data, questId) {
  if (data.questId !== questId || data.pageInfo?.type !== 5 || data.pageInfo.typeId !== questId
      || typeof data.infoboxMarkup !== 'string') throw new Error(`Invalid quest page: ${questId}`);
  const starters = new Map();
  function add(kind, id, name) {
    if (!['npc','item','object'].includes(kind) || !Number.isSafeInteger(id) || id<=0 || !name) {
      throw new Error(`Invalid starter for ${questId}`);
    }
    const key = kind + ':' + id;
    if (!starters.has(key)) starters.set(key, {kind,id,name});
  }
  for (const block of data.infoboxMarkup.matchAll(/\[li\]([\s\S]*?)\[\/li\]/g)) {
    if (!/\[icon name=quest-start(?:-[\w-]+)?\]/.test(block[1])) continue;
    if (/\[icon name=quest-end(?:-[\w-]+)?\]/.test(block[1])) throw new Error(`Mixed starter/receiver block: ${questId}`);
    let found = false;
    for (const entity of block[1].matchAll(/\[url=(?:https:\/\/www\.wowhead\.com)?\/forever\/(?:ru\/)?(npc|item|object)=(\d+)(?:\/[^\]]*)?\]([^\[]+)\[\/url\]/g)) {
      add(entity[1],Number(entity[2]),entity[3]); found = true;
    }
    for (const entity of block[1].matchAll(/\b(NPC|Object|Item) #(\d+)\b/g)) {
      add(entity[1].toLowerCase(),Number(entity[2]),entity[0]); found = true;
    }
    if (!found) throw new Error(`Unrecognized starter markup: ${questId}`);
  }
  // Maps can expose additional starters collapsed behind "and N more" in facts.
  // Only point=start counts; objectives and turn-in NPCs are deliberately ignored.
  for (const zone of Object.values(data.mapper?.objectives || {})) {
    for (const points of zone.levels || []) {
      for (const point of points || []) {
        if (point.point === 'start') add({1:'npc',2:'object',3:'item'}[point.type],point.id,point.name);
      }
    }
  }
  return {questId,starters:[...starters.values()].sort((a,b)=>a.kind.localeCompare(b.kind)||a.id-b.id)};
}

function russianNames() {
  const ast=lua.parse(fs.readFileSync(path.join(root,'src/Index.lua'),'latin1'),{encodingMode:'pseudo-latin1'});
  const table=ast.body.find(n=>n.type==='AssignmentStatement'&&n.variables[0].name==='WowVoiceIndex').init[0];
  const names=new Map();
  for(const title of table.fields) for(const row of title.value.fields) {
    const entry=Object.fromEntries(row.value.fields.map(f=>[f.key.name,f.value.value]));
    for(const [id,name] of [[entry.i,entry.n],[entry.ei,entry.en]]) {
      if(id>0 && name) {
        const value=Buffer.from(name,'latin1').toString('utf8');
        if(!names.has(id)) names.set(id,value);
        else if(names.get(id)!==value) names.set(id,null);
      }
    }
  }
  return names;
}

function render(manifest) {
  if(manifest.source!==source || !Array.isArray(manifest.quests) || !manifest.quests.length) throw new Error('Invalid manifest');
  const ids=new Set(), counts={npc:0,item:0,object:0,multiple:0,unknown:0};
  const lines=['-- Generated by tools/import-forever-speakers.js; do not edit.',
    '-- Quest-starter facts: Wowhead Forever, snapshot published by Forever Quest Pins.',
    '-- Source: https://github.com/TylerAkins/forever-quest-markers/tree/'+manifest.commit+'/data/forever-quests',
    '-- Full provenance and coverage stay in docs/internal/forever-speakers-manifest.json.',
    '-- false blocks guesses for confirmed non-NPC/multiple starters.', 'WowVoiceForeverSpeakers = {'];
  for(const q of manifest.quests) {
    if(!Number.isSafeInteger(q.questId)||q.questId<=0||ids.has(q.questId)) throw new Error('Invalid or duplicate quest ID');
    ids.add(q.questId);
    for(const s of q.starters) {
      if(!['npc','item','object'].includes(s.kind)||!Number.isSafeInteger(s.id)||s.id<=0
          ||typeof s.name!=='string'||!s.name||/[\x00-\x1f]/.test(s.name)) throw new Error('Invalid starter');
    }
    const status=!q.starters.length?'unknown':q.starters.length>1?'multiple':q.starters[0].kind;
    counts[status]++;
    if(status==='npc') {
      const s=q.starters[0], name=(s.nameRU||s.name).replace(/\\/g,'\\\\').replace(/"/g,'\\"');
      lines.push(`    [${q.questId}] = { npcID = ${s.id}, name = "${name}" },`);
    } else if(status!=='unknown') lines.push(`    [${q.questId}] = false, -- ${status}`);
  }
  lines.push('}', '');
  return {lua:lines.join('\n'),counts};
}

function importSnapshot(directory,commit) {
  if(!/^[a-f0-9]{40}$/.test(commit)) throw new Error('Provide the snapshot commit SHA');
  const metadata=JSON.parse(fs.readFileSync(path.join(directory,'manifest.json'),'utf8'));
  if(metadata.dataEnv!==16) throw new Error('Expected Forever data environment 16');
  const indexBytes=fs.readFileSync(path.join(directory,'quest_index.json'));
  const index=JSON.parse(indexBytes), names=russianNames();
  const ids=Object.keys(index).map(Number).sort((a,b)=>a-b);
  const quests=[], missing=[], rejected=[];
  for(const id of ids) {
    if(index[id].id!==id) throw new Error('Catalog ID mismatch');
    const file=path.join(directory,'details',id+'.json');
    if(!fs.existsSync(file)) {missing.push(id);continue;}
    const bytes=fs.readFileSync(file), data=JSON.parse(bytes);
    let q;
    try { q=questRecord(data,id); }
    catch(error) { rejected.push({questId:id,reason:error.message,sha256:sha256(bytes)});continue; }
    q.sha256=sha256(bytes);
    q.fetchedAt=data.fetchedAt;
    for(const s of q.starters) if(s.kind==='npc'&&names.get(s.id)) s.nameRU=names.get(s.id);
    quests.push(q);
  }
  return {source,commit,upstream:'https://www.wowhead.com/forever/',
    catalogSha256:sha256(indexBytes),catalogCount:ids.length,missing,rejected,quests};
}

function main() {
  const args=process.argv.slice(2);
  if(args.length!==0&&args.length!==2) throw new Error('Usage: node tools/import-forever-speakers.js [<data/forever-quests directory> <commit SHA>]');
  const manifest=args.length?importSnapshot(path.resolve(args[0]),args[1]):JSON.parse(fs.readFileSync(manifestPath,'utf8'));
  const result=render(manifest);
  if(args.length) fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
  fs.writeFileSync(path.join(root,'src/ForeverSpeakers.lua'),result.lua);
  console.log(JSON.stringify({catalog:manifest.catalogCount,missing:manifest.missing.length,rejected:manifest.rejected.length,...result.counts}));
}
module.exports={questRecord,render,importSnapshot};
if(require.main===module) {try{main();}catch(error){console.error(error);process.exitCode=1;}}
