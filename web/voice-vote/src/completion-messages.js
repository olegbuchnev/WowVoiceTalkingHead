// Draw every message once before reshuffling; avoid a repeat at the boundary.
export function createCompletionMessages(random=Math.random) {
  let remaining=[],previous;
  return {next() {
    if(!remaining.length) {
      remaining=[...completionMessages];
      for(let i=remaining.length-1;i>0;i--) {
        const j=Math.floor(random()*(i+1));
        [remaining[i],remaining[j]]=[remaining[j],remaining[i]];
      }
      if(remaining[0]===previous) [remaining[0],remaining[1]]=[remaining[1],remaining[0]];
    }
    previous=remaining.shift();
    return previous;
  }};
}
